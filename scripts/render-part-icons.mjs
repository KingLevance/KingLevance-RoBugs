/**
 * Renders every catalog part's 3D model to a PNG icon (assets/parts/<id>.png)
 * and regenerates src/components/part-icons.ts. Icons therefore always match
 * the in-game models. Re-run after changing src/render/models.ts or the catalog:
 *
 *   node scripts/render-part-icons.mjs
 *
 * Needs a Chromium with WebGL (Playwright) and Python 3 + Pillow for downscaling.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const { chromium } = require('playwright');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'assets/parts');
const RENDER = 512;
const FINAL = 192;

const entry = `
import * as THREE from 'three';
import { buildPart, IDLE } from '@/render/models';
import { PARTS } from '@/game/parts';

window.renderIcons = (size) => {
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = size;
  const renderer = new THREE.WebGLRenderer({ canvas, alpha: true, antialias: true, preserveDrawingBuffer: true });
  renderer.setClearColor(0x000000, 0);
  const dir = new THREE.Vector3(0.8, 0.8, -1).normalize(); // front-right, from above
  const out = {};
  for (const p of PARTS) {
    const scene = new THREE.Scene();
    scene.add(new THREE.HemisphereLight(0xfff4e0, 0x30343c, 1.4));
    const sun = new THREE.DirectionalLight(0xffffff, 1.6);
    sun.position.set(6, 14, -8);
    scene.add(sun);
    const m = buildPart(p.id, 0, 0);
    m.animate({ t: 0.6, ...IDLE });
    m.tint(1, false);
    scene.add(m.root);
    const sphere = new THREE.Box3().setFromObject(m.root).getBoundingSphere(new THREE.Sphere());
    const r = sphere.radius * 1.02;
    const cam = new THREE.OrthographicCamera(-r, r, r, -r, 0.1, 50);
    cam.position.copy(sphere.center).addScaledVector(dir, 10);
    cam.lookAt(sphere.center);
    renderer.render(scene, cam);
    out[p.id] = canvas.toDataURL('image/png');
  }
  return out;
};
`;

const bundle = await esbuild.build({
  stdin: { contents: entry, resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'iife',
  write: false,
  alias: { '@': path.join(root, 'src') },
  logLevel: 'error',
});

const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
page.on('pageerror', (e) => console.error('page error:', e));
await page.setContent('<html><body></body></html>');
await page.addScriptTag({ content: bundle.outputFiles[0].text });
const icons = await page.evaluate((size) => window.renderIcons(size), RENDER);
await browser.close();

mkdirSync(outDir, { recursive: true });
const ids = Object.keys(icons);
for (const id of ids) writeFileSync(path.join(outDir, `${id}.png`), Buffer.from(icons[id].split(',')[1], 'base64'));

// High-quality downscale.
execFileSync('python3', [
  '-c',
  `import sys
from PIL import Image
for f in sys.argv[2:]:
    Image.open(f).resize((int(sys.argv[1]),) * 2, Image.LANCZOS).save(f, optimize=True)`,
  String(FINAL),
  ...ids.map((id) => path.join(outDir, `${id}.png`)),
]);

const lines = ids.map((id) => `  '${id}': require('@/assets/parts/${id}.png'),`).join('\n');
writeFileSync(
  path.join(root, 'src/components/part-icons.ts'),
  `// GENERATED by scripts/render-part-icons.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

/** Rendered thumbnail of each part's 3D model, keyed by part id. */
export const PART_ICONS: Record<string, ImageSourcePropType> = {
${lines}
};
`,
);
console.log(`Rendered ${ids.length} part icons → assets/parts/`);
