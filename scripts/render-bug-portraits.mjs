/**
 * Renders a portrait of every campaign opponent (assets/bugs/<id>.png) and
 * regenerates src/components/bug-portraits.ts. Re-run after changing an
 * opponent's build or the part models:
 *
 *   node scripts/render-bug-portraits.mjs
 *
 * Needs a Chromium with WebGL (Playwright) and Python 3 + Pillow for downscaling.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const { chromium } = require('playwright');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'assets/bugs');
const RENDER = 640;
const FINAL = 256;

const entry = `
import * as THREE from 'three';
import { buildBugModel } from '@/render/bug-model';
import { IDLE } from '@/render/models';
import { OPPONENTS } from '@/game/opponents';

window.renderPortraits = (size) => {
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = size;
  const renderer = new THREE.WebGLRenderer({ canvas, alpha: true, antialias: true, preserveDrawingBuffer: true });
  renderer.setClearColor(0x000000, 0);
  const dir = new THREE.Vector3(-0.55, 0.85, -1).normalize(); // front-left, from above
  const out = {};
  for (const o of OPPONENTS) {
    const scene = new THREE.Scene();
    scene.add(new THREE.HemisphereLight(0xfff4e0, 0x30343c, 1.4));
    const sun = new THREE.DirectionalLight(0xffffff, 1.6);
    sun.position.set(-6, 14, -8);
    scene.add(sun);
    const rim = new THREE.DirectionalLight(0xffc27a, 0.8);
    rim.position.set(6, 4, 8);
    scene.add(rim);
    const bug = buildBugModel(o.build.placements);
    bug.animate({ t: 0.9, ...IDLE });
    scene.add(bug.root);
    const sphere = new THREE.Box3().setFromObject(bug.root).getBoundingSphere(new THREE.Sphere());
    const r = sphere.radius * 0.82;
    const cam = new THREE.OrthographicCamera(-r, r, r, -r, 0.1, 80);
    cam.position.copy(sphere.center).addScaledVector(dir, 20);
    cam.lookAt(sphere.center);
    renderer.render(scene, cam);
    out[o.id] = canvas.toDataURL('image/png');
  }
  return out;
};
`;

const bundle = await esbuild.build({
  stdin: { contents: entry, resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'iife',
  write: false,
  alias: { '@': path.join(root, 'src') },
  logLevel: 'error',
});

const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
page.on('pageerror', (e) => console.error('page error:', e));
await page.setContent('<html><body></body></html>');
await page.addScriptTag({ content: bundle.outputFiles[0].text });
const shots = await page.evaluate((size) => window.renderPortraits(size), RENDER);
await browser.close();

mkdirSync(outDir, { recursive: true });
const ids = Object.keys(shots);
for (const id of ids) writeFileSync(path.join(outDir, `${id}.png`), Buffer.from(shots[id].split(',')[1], 'base64'));

execFileSync('python3', [
  '-c',
  `import sys
from PIL import Image
for f in sys.argv[2:]:
    Image.open(f).resize((int(sys.argv[1]),) * 2, Image.LANCZOS).save(f, optimize=True)`,
  String(FINAL),
  ...ids.map((id) => path.join(outDir, `${id}.png`)),
]);

const lines = ids.map((id) => `  ${id}: require('@/assets/bugs/${id}.png'),`).join('\n');
writeFileSync(
  path.join(root, 'src/components/bug-portraits.ts'),
  `// GENERATED by scripts/render-bug-portraits.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

/** Rendered portrait of each campaign opponent's bug, keyed by opponent id. */
export const BUG_PORTRAITS: Record<string, ImageSourcePropType> = {
${lines}
};
`,
);
console.log(`Rendered ${ids.length} bug portraits → assets/bugs/`);
